import assert from 'node:assert/strict'

export async function checkReallocations(page, base, artifacts, browser) {
  assert.equal(process.env.SMOKE_ISOLATED, '1')
  const refs = await page.evaluate(async () => {
    const { apiClient } = await import('/src/api/client.js')
    const { data: me } = await apiClient.get('/me')
    const root = `/entities/${me.activeEntity.id}/inventory`
    const read = async path => (await apiClient.get(`${root}/${path}`)).data.items
    return { warehouse: (await read('warehouses'))[0].id, sku: (await read('skus')).find(s => s.code === 'ZARF-A3').id,
      pools: Object.fromEntries((await read('pools')).map(p => [p.code,p.id])), movement: (await read('movement-types')).find(m => m.effect === 'REALLOCATION').id }
  })
  await page.getByRole('tab', { name: 'Allocation & borrowing', exact: true }).click()
  await page.getByText('No allocation requests yet.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Check allocation', exact: true }).click()
  await page.getByLabel('Allocation warehouse', { exact: true }).selectOption(refs.warehouse)
  await page.getByLabel('Allocation SKU', { exact: true }).selectOption(refs.sku)
  await page.getByLabel('Destination pool', { exact: true }).selectOption(refs.pools.AF)
  await page.getByLabel('Total quantity needed', { exact: true }).fill('100')
  await page.getByLabel('Allocation posting date', { exact: true }).fill('2026-02-11')
  await page.getByRole('button', { name: 'Preview availability', exact: true }).click()
  await page.getByText('Destination: 30.000000', { exact: true }).waitFor()
  await page.getByText('GENERAL: 60.000000', { exact: true }).waitFor()
  await page.getByText('Shortfall: 10.000000', { exact: true }).waitFor()
  await page.getByLabel('Request reference', { exact: true }).fill('BROWSER-BORROW')
  await page.getByLabel('Quantity to transfer', { exact: true }).fill('10')
  await page.getByLabel('Source pool', { exact: true }).selectOption(refs.pools.CM)
  await page.getByLabel('Reallocation movement type', { exact: true }).selectOption(refs.movement)
  await page.getByLabel('Request reason', { exact: true }).fill('Approved destination demand')
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: `${artifacts}/allocation-planner-mobile.png`, fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: 'Submit transfer request', exact: true }).click()
  await page.getByRole('heading', { name: 'Request BROWSER-BORROW', exact: true }).waitFor()
  await page.getByText('Another authorized person must review this country borrowing request.', { exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Approve request', exact: true }).count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Execute transfer', exact: true }).count(), 0)
  await page.screenshot({ path: `${artifacts}/reallocation-request-desktop.png`, fullPage: true })
  const reviewer = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  try {
    await reviewer.goto(`${base}/inventory`)
    await reviewer.getByLabel('Workspace code').fill(process.env.SMOKE_TENANT)
    await reviewer.getByLabel('Email', { exact: true }).fill(process.env.SMOKE_INVENTORY_REVIEWER_EMAIL)
    await reviewer.getByLabel('Password', { exact: true }).fill(process.env.SMOKE_PASSWORD)
    await reviewer.getByRole('button', { name: 'Sign in', exact: true }).click()
    await reviewer.getByRole('heading', { name: 'Inventory setup', exact: true }).waitFor()
    await reviewer.getByRole('tab', { name: 'Allocation & borrowing', exact: true }).click()
    await reviewer.getByRole('button', { name: 'View request BROWSER-BORROW', exact: true }).click()
    await reviewer.getByLabel('Review or cancellation reason').fill('Country manager confirmed release')
    await reviewer.getByRole('button', { name: 'Approve request', exact: true }).click()
    await reviewer.getByText('Status: APPROVED', { exact: true }).waitFor()
    assert.equal(await reviewer.getByRole('button', { name: 'Execute transfer', exact: true }).count(), 0)
  } finally { await reviewer.close() }
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await page.getByRole('button', { name: 'Execute transfer', exact: true }).click()
  await page.getByText('Status: EXECUTED', { exact: true }).waitFor()
  await page.getByRole('cell', { name: '5000.000000 TRY', exact: true }).waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.equal(await page.locator('header').count(), 0)
  await page.screenshot({ path: `${artifacts}/reallocation-executed-mobile.png`, fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('tab', { name: 'Stock balances', exact: true }).click()
  await page.getByRole('cell', { name: '100.000000', exact: true }).first().waitFor()
  await page.getByRole('tab', { name: 'Pool balances', exact: true }).click()
  await page.getByRole('cell', { name: '40.000000', exact: true }).first().waitFor()
  await page.getByRole('tab', { name: 'Pool ledger', exact: true }).click()
  await page.getByRole('cell', { name: '-10.000000', exact: true }).waitFor()
  await page.getByRole('tab', { name: 'Receipts', exact: true }).click()
  await page.getByRole('button', { name: 'View receipt BROWSER-RECEIPT', exact: true }).click()
  await page.getByText('CM: 10.000000', { exact: false }).waitFor()
  console.log('PASS: allocation preview, explicit country request, independent browser reviewer, execution, unchanged physical/original receipt, signed ledger and mobile layout.')
}
