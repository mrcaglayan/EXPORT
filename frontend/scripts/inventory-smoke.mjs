import assert from 'node:assert/strict'

export async function checkInventory(page, base, artifacts) {
  assert.equal(process.env.SMOKE_ISOLATED, '1')
  await page.goto(`${base}/inventory`)
  await page.getByRole('heading', { name: 'Inventory setup', exact: true }).waitFor()
  const tab = name => page.getByRole('tab', { name, exact: true }).click()
  await page.getByRole('button', { name: 'Add warehouse', exact: true }).click()
  await page.getByLabel('Code', { exact: true }).fill('IST')
  await page.getByLabel('Name', { exact: true }).fill('İstanbul warehouse')
  await page.getByLabel('Location', { exact: true }).fill('İstanbul, Türkiye')
  await page.getByRole('button', { name: 'Save warehouse', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'İstanbul warehouse' }).waitFor()
  await tab('Destination pools')
  for (const code of ['GENERAL', 'AF', 'CM']) {
    await page.getByRole('button', { name: 'Add pool', exact: true }).click()
    await page.getByLabel('Name', { exact: true }).fill(`${code} allocation`)
    if (code !== 'GENERAL') {
      await page.getByLabel('Pool kind', { exact: true }).selectOption('COUNTRY')
      await page.getByLabel('Country', { exact: true }).selectOption(code)
    }
    await page.getByRole('button', { name: 'Save pool', exact: true }).click()
    await page.getByRole('row').filter({ hasText: `${code} allocation` }).waitFor()
  }
  assert.equal(await page.getByRole('row').count(), 4)
  await page.getByRole('button', { name: 'Add pool', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Duplicate general')
  await page.getByRole('button', { name: 'Save pool', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: 'already exists' }).waitFor()
  assert.equal(await page.getByLabel('Name', { exact: true }).inputValue(), 'Duplicate general')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByLabel('Filter pool kind').selectOption('COUNTRY')
  await page.getByRole('row').filter({ hasText: 'AF allocation' }).waitFor()
  assert.equal(await page.getByRole('row').count(), 3)
  await page.getByRole('button', { name: 'Edit AF', exact: true }).click()
  assert.equal(await page.getByLabel('Pool kind', { exact: true }).isDisabled(), true)
  assert.equal(await page.getByLabel('Country', { exact: true }).isDisabled(), true)
  await page.getByLabel('Status', { exact: true }).selectOption('false')
  await page.getByRole('button', { name: 'Save pool', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'AF allocation' }).getByRole('cell', { name: 'Inactive', exact: true }).waitFor()
  await page.getByLabel('Filter status').selectOption('false')
  await page.getByRole('row').filter({ hasText: 'AF allocation' }).waitFor()
  assert.equal(await page.getByRole('row').count(), 2)
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'GENERAL allocation' }).waitFor()
  await page.screenshot({ path: `${artifacts}/inventory-pools-desktop.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Add pool', exact: true }).click()
  assert.equal(await page.locator('header').count(), 0)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: `${artifacts}/inventory-pools-mobile.png`, fullPage: true })
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 1000 })

  await tab('Movement types')
  await page.getByRole('button', { name: 'Add movement type', exact: true }).click()
  await page.getByLabel('Code', { exact: true }).fill('POOL_MOVE')
  await page.getByLabel('Name', { exact: true }).fill('Pool reallocation')
  await page.getByLabel('Movement effect').selectOption('REALLOCATION')
  await page.getByRole('button', { name: 'Save movement type', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'POOL_MOVE' }).waitFor()
  await page.getByRole('button', { name: 'Edit POOL_MOVE', exact: true }).click()
  assert.equal(await page.getByLabel('Movement effect').isDisabled(), true)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  // The accounting flow closed JAN. Add an open FEB only in this disposable DB.
  const periodId = await page.evaluate(async () => {
    const { apiClient } = await import('/src/api/client.js')
    const { data: me } = await apiClient.get('/me')
    const root = `/entities/${me.activeEntity.id}/accounting`
    const { data: years } = await apiClient.get(`${root}/fiscal-years`)
    return (await apiClient.post(`${root}/periods`, { code: 'FEB', fiscalYearId: years.items[0].id, startDate: '2026-02-01', endDate: '2026-02-28' }, { headers: { 'Idempotency-Key': crypto.randomUUID() } })).data.period.id
  })
  await tab('Inventory periods')
  await page.getByRole('button', { name: 'Add inventory period', exact: true }).click()
  const period = page.getByLabel('Accounting period', { exact: true })
  await period.selectOption({ label: 'JAN — 2026-01-01 → 2026-01-31 · CLOSED' })
  await page.getByRole('button', { name: 'Save inventory period', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: 'Choose an open accounting period' }).waitFor()
  await period.selectOption(periodId)
  await page.getByRole('button', { name: 'Save inventory period', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'FEB' }).getByRole('cell', { name: '2026-02-01 → 2026-02-28', exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: /Close|Post/ }).count(), 0)
  await tab('Audit trail')
  await page.getByRole('cell', { name: 'inventory.periods.created', exact: true }).waitFor()
  await page.screenshot({ path: `${artifacts}/inventory-audit.png`, fullPage: true })
  await page.reload()
  await page.getByRole('row').filter({ hasText: 'İstanbul warehouse' }).waitFor()
  const entity = page.locator('aside').getByLabel('Legal entity')
  const original = await entity.inputValue()
  const other = await entity.locator('option').evaluateAll((options, current) => options.find(option => option.value !== current).value, original)
  await entity.selectOption(other)
  await page.getByText('No warehouses configured yet.', { exact: true }).waitFor()
  await entity.selectOption(original)
  await page.getByRole('row').filter({ hasText: 'İstanbul warehouse' }).waitFor()
  console.log('PASS: Inventory warehouse and GENERAL/AF/CM forms, duplicate/inactive guards, pool filters, fixed movement effect, calendar-linked period/closed guard, audit, mobile, reload and entity isolation.')
}
