import assert from 'node:assert/strict'

export async function checkClassification(page, base, artifacts) {
  assert.equal(process.env.SMOKE_ISOLATED, '1')
  await page.goto(`${base}/products`)
  const tab = name => page.getByRole('tab', { name, exact: true }).click()
  await tab('Specification definitions')
  await page.getByRole('button', { name: 'Add specification definition', exact: true }).click()
  await page.getByLabel('Code', { exact: true }).fill('SIZE')
  await page.getByLabel('Name', { exact: true }).fill('Paper size')
  await page.getByLabel('Defines stock identity').check()
  await page.getByRole('button', { name: 'Save specification definition' }).click()
  await page.getByRole('row').filter({ hasText: 'SIZE' }).waitFor()
  await tab('Suppliers')
  await page.getByRole('button', { name: 'Add supplier', exact: true }).click()
  await page.getByLabel('Code', { exact: true }).fill('SUP-TEST')
  await page.getByLabel('Name', { exact: true }).fill('Synthetic supplier')
  await page.getByRole('button', { name: 'Save supplier', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'SUP-TEST' }).waitFor()
  await tab('SKUs')
  await page.getByRole('button', { name: 'Details ZARF-A3', exact: true }).click()
  await page.getByRole('heading', { name: 'Specifications', exact: true }).waitFor()
  const specification = page.getByRole('form', { name: 'SKU specification', exact: true })
  await specification.getByLabel('Specification', { exact: true }).selectOption({ label: 'SIZE — Paper size' })
  await specification.getByLabel('Specification value', { exact: true }).fill('A3')
  await specification.getByRole('button', { name: 'Save specification', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Specification saved.' }).waitFor()
  await page.getByRole('button', { name: 'Set SIZE', exact: true }).click()
  await specification.getByLabel('Specification value', { exact: true }).fill('A4')
  await specification.getByRole('button', { name: 'Save specification', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: 'defines stock identity' }).waitFor()
  assert.equal(await specification.getByLabel('Specification value', { exact: true }).inputValue(), 'A4')
  const newGtip = page.getByRole('form', { name: 'New GTİP entry', exact: true })
  await newGtip.getByLabel('GTİP code', { exact: true }).fill('000000000001')
  await newGtip.getByLabel('Classification source').fill('Synthetic classification fixture; not an assigned real code')
  await newGtip.getByLabel('Effective from', { exact: true }).fill('2026-01-01')
  await newGtip.getByRole('button', { name: 'Add GTİP entry', exact: true }).click()
  const gtipRow = page.getByRole('row').filter({ hasText: '000000000001' })
  await gtipRow.getByRole('cell', { name: 'PENDING', exact: true }).waitFor()
  await gtipRow.getByRole('button', { name: 'Review GTİP 000000000001', exact: true }).click()
  let review = page.getByRole('form', { name: 'Review record', exact: true })
  await review.getByLabel('Review reason').fill('Compared product specifications')
  await review.getByRole('button', { name: 'Record review' }).click()
  await gtipRow.getByRole('cell', { name: 'REVIEWED', exact: true }).waitFor()
  await gtipRow.getByRole('button', { name: 'Review GTİP 000000000001', exact: true }).click()
  review = page.getByRole('form', { name: 'Review record', exact: true })
  await review.getByLabel('Review reason').fill('Synthetic evidence checked')
  await review.getByLabel('Broker name').fill('Synthetic broker')
  await review.getByLabel('Verification reference').fill('TEST-REFERENCE-1')
  await review.getByLabel('Broker verification date').fill('2026-01-01')
  await review.getByRole('button', { name: 'Record review' }).click()
  await gtipRow.getByRole('cell', { name: 'VERIFIED', exact: true }).waitFor()
  await gtipRow.getByRole('button', { name: 'Set end date' }).click()
  const end = page.getByRole('form', { name: 'End GTİP date range' })
  await end.getByLabel('Last effective date').fill('2026-06-30')
  await end.getByLabel('Date change reason').fill('New classification from July')
  await end.getByRole('button', { name: 'Save end date' }).click()
  await gtipRow.getByRole('cell', { name: '2026-01-01 → 2026-06-30', exact: true }).waitFor()
  for (const [date, succeeds] of [['2026-06-30', false], ['2026-07-01', true]]) {
    await newGtip.getByLabel('GTİP code', { exact: true }).fill('000000000002')
    await newGtip.getByLabel('Classification source').fill('Synthetic successor')
    await newGtip.getByLabel('Effective from', { exact: true }).fill(date)
    await newGtip.getByRole('button', { name: 'Add GTİP entry', exact: true }).click()
    if (!succeeds) await page.getByRole('alert').filter({ hasText: 'date range' }).waitFor()
    else await page.getByRole('row').filter({ hasText: '000000000002' }).waitFor()
  }
  await page.screenshot({ path: `${artifacts}/product-specifications-gtip.png`, fullPage: true })
  await tab('Supplier aliases')
  await page.getByRole('button', { name: 'Propose alias' }).click()
  const aliasForm = page.getByRole('form', { name: 'New supplier alias' })
  await aliasForm.getByLabel('Supplier', { exact: true }).selectOption({ label: 'SUP-TEST — Synthetic supplier' })
  await aliasForm.getByLabel('Supplier item code').fill('SOURCE-A3')
  const original = '  Original A3\nSupplier wording  '
  await aliasForm.getByLabel('Original supplier description').fill(original)
  await aliasForm.getByLabel('Candidate SKU', { exact: true }).selectOption({ label: 'ZARF-A3 — ZARF-A3 envelope' })
  await aliasForm.getByLabel('Alias source reference').fill('TEST-DOCUMENT-1')
  await aliasForm.getByRole('button', { name: 'Save alias proposal' }).click()
  const aliasRow = page.getByRole('row').filter({ hasText: 'SOURCE-A3' })
  await aliasRow.getByRole('cell', { name: 'PENDING', exact: true }).waitFor()
  assert.equal(await aliasRow.locator('p').filter({ hasText: 'Original A3' }).textContent(), original)
  await page.getByText('Check an exact supplier match', { exact: true }).click()
  const match = page.getByRole('form', { name: 'Check supplier match' })
  await match.getByLabel('Supplier', { exact: true }).selectOption({ label: 'SUP-TEST — Synthetic supplier' })
  await match.getByLabel('Supplier item code').fill('SOURCE-A3')
  await match.getByLabel('Original supplier description').fill(original)
  await match.getByRole('button', { name: 'Check match' }).click()
  await match.getByRole('status').filter({ hasText: 'No verified exact match' }).waitFor()
  for (const status of ['REVIEWED', 'VERIFIED']) {
    await aliasRow.getByRole('button', { name: 'Review alias SOURCE-A3 revision 1', exact: true }).click()
    review = page.getByRole('form', { name: 'Review record', exact: true })
    await review.getByLabel('Decision', { exact: true }).selectOption(status)
    await review.getByLabel('Review reason').fill('Synthetic same-goods review')
    await review.getByRole('button', { name: 'Record review' }).click()
    await aliasRow.getByRole('cell', { name: status, exact: true }).waitFor()
  }
  await match.getByRole('button', { name: 'Check match' }).click()
  await match.getByRole('status').filter({ hasText: 'Verified match: ZARF-A3' }).waitFor()
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Loading aliases' }).waitFor({ state: 'hidden' })
  assert.equal(await match.getByRole('status').count(), 0)
  await match.getByLabel('Original supplier description').fill('Similar wording')
  await match.getByRole('button', { name: 'Check match' }).click()
  await match.getByRole('status').filter({ hasText: 'No verified exact match' }).waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: `${artifacts}/product-aliases-mobile.png`, fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.reload()
  await tab('Supplier aliases')
  await page.getByRole('row').filter({ hasText: 'SOURCE-A3' }).getByRole('cell', { name: 'VERIFIED', exact: true }).waitFor()
  await page.screenshot({ path: `${artifacts}/product-aliases-desktop.png`, fullPage: true })
  console.log('PASS: typed SKU detail, stock identity guard, GTIP review/evidence/end dates/overlap, original alias wording, verified-only exact match, reload and mobile layout.')
}
