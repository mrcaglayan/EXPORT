import assert from 'node:assert/strict'

export async function checkReservations(page, base, artifacts) {
  assert.equal(process.env.SMOKE_ISOLATED, '1')
  const refs = await page.evaluate(async () => {
    const { apiClient } = await import('/src/api/client.js')
    const { data: me } = await apiClient.get('/me')
    const root = `/entities/${me.activeEntity.id}/inventory`
    const read = async resource => (await apiClient.get(`${root}/${resource}`)).data.items
    let movement = (await read('movement-types')).find(m => m.effect === 'ISSUE')
    if (!movement) movement = (await apiClient.post(`${root}/movement-types`, { code: 'SHIP', name: 'Physical dispatch', effect: 'ISSUE' }, { headers: { 'Idempotency-Key': crypto.randomUUID() } })).data.item
    const skus = await read('skus')
    return { warehouse: (await read('warehouses'))[0].id, af: (await read('pools')).find(p => p.code === 'AF').id,
      sku: skus.find(s => s.code === 'ZARF-A3').id, free: skus.find(s => s.code === 'ZARF-A5').id, movement: movement.id }
  })
  await page.getByRole('tab', { name: 'Reservations', exact: true }).click()
  await page.getByText('No matching reservations.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'New reservation', exact: true }).click()
  await page.getByLabel('Reservation reference', { exact: true }).fill('BROWSER-RESERVE')
  await page.getByLabel('Reservation date', { exact: true }).fill('2026-02-11')
  await page.getByLabel('Reservation warehouse', { exact: true }).selectOption(refs.warehouse)
  await page.getByLabel('Reservation destination', { exact: true }).selectOption(refs.af)
  await page.getByLabel('Reservation reason', { exact: true }).fill('Confirmed shipment including samples')
  await page.getByLabel('Reservation SKU', { exact: true }).selectOption(refs.sku)
  await page.getByLabel('Line quantity', { exact: true }).fill('50')
  await page.getByRole('button', { name: 'Add reservation line', exact: true }).click()
  await page.getByLabel('Reservation SKU', { exact: true }).selectOption(refs.free)
  await page.getByLabel('Line quantity', { exact: true }).fill('1')
  await page.getByRole('button', { name: 'Add reservation line', exact: true }).click()
  assert.equal(await page.getByText('NaN', { exact: true }).count(), 0)
  await page.getByRole('button', { name: 'Reserve stock', exact: true }).click()
  await page.getByRole('heading', { name: 'Reservation BROWSER-RESERVE', exact: true }).waitFor()
  await page.getByRole('cell', { name: '50.000000', exact: true }).first().waitFor()
  await page.getByLabel('Reservation action', { exact: true }).selectOption('release')
  await page.getByLabel('Action quantity line 1', { exact: true }).fill('5')
  await page.getByLabel('Release reason', { exact: true }).fill('Reduce shipment quantity')
  await page.getByRole('button', { name: 'Release selected quantities', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Reserved stock released.' }).waitFor()
  await page.getByRole('cell', { name: '45.000000', exact: true }).waitFor()
  await page.getByText('Reserved source layers', { exact: true }).click()
  await page.screenshot({ path: `${artifacts}/reservation-detail-desktop.png`, fullPage: true })
  await page.getByLabel('Reservation action', { exact: true }).selectOption('issue')
  await page.getByLabel('Action quantity line 1', { exact: true }).fill('42')
  await page.getByRole('button', { name: 'Use remaining line 2', exact: true }).click()
  await page.getByLabel('Dispatch description', { exact: true }).fill('Physical shipment and free sample')
  await page.getByLabel('Dispatch reference', { exact: true }).fill('BROWSER-DISPATCH')
  await page.getByLabel('Physical dispatch date', { exact: true }).fill('2026-02-12')
  await page.getByLabel('Dispatch posting date', { exact: true }).fill('2026-02-12')
  await page.getByLabel('Issue movement type', { exact: true }).selectOption(refs.movement)
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: `${artifacts}/reservation-dispatch-mobile.png`, fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: 'Post dispatch', exact: true }).click()
  await page.getByRole('heading', { name: 'Dispatch BROWSER-DISPATCH', exact: true }).waitFor()
  await page.getByText('Stock cost consumed: 21000.000000 TRY', { exact: true }).waitFor()
  await page.getByRole('cell', { name: '0.000000 TRY', exact: true }).waitFor()
  await page.screenshot({ path: `${artifacts}/dispatch-sources-desktop.png`, fullPage: true })
  await page.getByRole('button', { name: 'Back from dispatch', exact: true }).click()
  await page.getByLabel('Reservation action', { exact: true }).selectOption('cancel')
  await page.getByLabel('Release reason', { exact: true }).fill('Cancel unshipped remainder')
  await page.getByRole('button', { name: 'Cancel remaining reservation', exact: true }).click()
  await page.getByText('CANCELLED', { exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Post dispatch', exact: true }).count(), 0)
  await page.getByRole('tab', { name: 'Stock balances', exact: true }).click()
  await page.getByRole('cell', { name: '58.000000', exact: true }).first().waitFor()
  await page.getByRole('tab', { name: 'Physical ledger', exact: true }).click()
  await page.getByRole('cell', { name: '-42.000000', exact: true }).waitFor()
  await page.getByRole('tab', { name: 'Dispatches', exact: true }).click()
  await page.getByRole('button', { name: 'View dispatch BROWSER-DISPATCH', exact: true }).click()
  await page.getByRole('heading', { name: 'Dispatch BROWSER-DISPATCH', exact: true }).waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.equal(await page.locator('header').count(), 0)
  await page.screenshot({ path: `${artifacts}/dispatch-detail-mobile.png`, fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('tab', { name: 'Receipts', exact: true }).click()
  await page.getByRole('button', { name: 'View receipt BROWSER-RECEIPT', exact: true }).click()
  await page.getByText('CM: 10.000000', { exact: false }).waitFor()
  console.log('PASS: multi-SKU reservation, partial release, reserved-layer dispatch/free sample, cancel remainder, immutable receipt, stock/ledger/source views and responsive layout.')
}
