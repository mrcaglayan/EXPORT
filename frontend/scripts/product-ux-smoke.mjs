import assert from 'node:assert/strict'

// Runs after the product/classification fixtures, exclusively in an owned test DB.
export async function checkProductUx(page, base, artifacts) {
  assert.equal(process.env.SMOKE_ISOLATED, '1')
  const tab = async name => {
    await page.getByRole('tab', { name, exact: true }).click()
    await page.getByRole('tab', { name, exact: true, selected: true }).waitFor()
  }
  await page.goto(`${base}/products?view=families`)
  await page.getByRole('button', { name: 'SKUs in ZARF', exact: true }).click()
  await page.getByRole('tab', { name: 'SKUs', exact: true, selected: true }).waitFor()
  assert.ok(new URL(page.url()).searchParams.get('skus.familyId'))
  await page.getByLabel('Search catalogue').fill('A3')
  await page.getByRole('button', { name: 'Details ZARF-A3', exact: true }).click()
  await page.getByRole('heading', { name: 'ZARF-A3 — ZARF-A3 envelope', exact: true }).waitFor()
  const detailUrl = page.url()
  const skuId = new URL(detailUrl).searchParams.get('sku')
  assert.ok(skuId)
  await page.reload()
  await page.getByRole('heading', { name: 'ZARF-A3 — ZARF-A3 envelope', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Back to SKUs' }).click()
  assert.equal(await page.getByLabel('Search catalogue').inputValue(), 'A3')
  await page.getByRole('row').filter({ hasText: 'ZARF-A3' }).waitFor()
  assert.equal(await page.getByRole('row').count(), 2)
  await page.goBack()
  await page.getByRole('heading', { name: 'Specifications', exact: true }).waitFor()

  // Refresh must read the SKU again; a bookmarked row snapshot is insufficient.
  await page.evaluate(async id => {
    const { apiClient } = await import('/src/api/client.js')
    const { data: profile } = await apiClient.get('/me')
    const path = `/entities/${profile.activeEntity.id}/products/skus/${id}`
    const { data: { item } } = await apiClient.get(path)
    await apiClient.patch(path, { name: 'A3 refreshed', description: item.description, familyId: item.familyId, active: true }, { headers: { 'Idempotency-Key': crypto.randomUUID() } })
  }, skuId)
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await page.getByRole('heading', { name: 'ZARF-A3 — A3 refreshed', exact: true }).waitFor()

  const gtip = page.getByRole('form', { name: 'New GTİP entry' })
  await gtip.getByLabel('GTİP code', { exact: true }).fill('123')
  assert.equal(await gtip.getByLabel('GTİP code', { exact: true }).evaluate(input => input.validity.patternMismatch), true)
  await gtip.getByLabel('GTİP code', { exact: true }).fill('000000000003')
  await gtip.getByLabel('Classification source').fill('Validation fixture')
  await gtip.getByLabel('Effective from', { exact: true }).fill('2027-02-01')
  await gtip.getByLabel('Effective to (optional)', { exact: true }).fill('2027-01-31')
  assert.equal(await gtip.getByLabel('Effective to (optional)', { exact: true }).evaluate(input => input.validity.rangeUnderflow), true)
  let writes = 0
  const countWrites = request => { if (request.method() === 'POST' && request.url().includes('/products/')) writes++ }
  page.on('request', countWrites)
  await gtip.getByRole('button', { name: 'Add GTİP entry' }).click()
  assert.equal(writes, 0)

  await tab('Suppliers')
  await page.getByRole('button', { name: 'Add supplier', exact: true }).click()
  await page.getByLabel('Code', { exact: true }).fill('VALIDATION')
  await page.getByLabel('Name', { exact: true }).fill('   ')
  await page.getByRole('button', { name: 'Save supplier', exact: true }).click()
  assert.equal(await page.getByLabel('Name', { exact: true }).evaluate(input => input.validity.customError), true)
  assert.equal(writes, 0)
  await page.getByLabel('Name', { exact: true }).fill('Valid wording')
  assert.equal(await page.getByLabel('Name', { exact: true }).evaluate(input => input.validity.valid), true)
  await page.getByLabel('Code', { exact: true }).fill('INVALID CODE')
  assert.equal(await page.getByLabel('Code', { exact: true }).evaluate(input => input.validity.patternMismatch), true)
  await page.getByLabel('Code', { exact: true }).fill('sup-test')
  await page.getByRole('status').filter({ hasText: 'Code SUP-TEST already exists (active)' }).waitFor()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  page.off('request', countWrites)

  // Filters include inactive references, whereas new-record pickers use active ones.
  const fixtures = await page.evaluate(async () => {
    const { apiClient } = await import('/src/api/client.js')
    const { data: profile } = await apiClient.get('/me')
    const root = `/entities/${profile.activeEntity.id}/products`
    const create = async (path, body) => (await apiClient.post(`${root}/${path}`, body, { headers: { 'Idempotency-Key': crypto.randomUUID() } })).data.item
    const family = await create('families', { code: 'ARCHIVED', name: 'Archived family', parentId: null })
    await apiClient.patch(`${root}/families/${family.id}`, { name: family.name, parentId: null, active: false }, { headers: { 'Idempotency-Key': crypto.randomUUID() } })
    const definition = await create('attribute-definitions', { code: 'WEIGHT', name: 'Test weight', dataType: 'DECIMAL', unitLabel: 'kg', definesStock: false })
    return { familyId: family.id, definitionId: definition.id }
  })
  await page.goto(`${base}/products`)
  await page.getByText('Filter by family', { exact: true }).click()
  await page.getByLabel('Filter family', { exact: true }).selectOption(fixtures.familyId)
  await page.getByText('No matching records. Change or clear the filters.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await page.getByRole('button', { name: 'Details ZARF-A3', exact: true }).click()
  const specification = page.getByRole('form', { name: 'SKU specification', exact: true })
  await specification.getByLabel('Specification', { exact: true }).selectOption(fixtures.definitionId)
  const value = specification.getByLabel('Specification value', { exact: true })
  for (const invalid of ['1,25', '1e3', '01', '0.1234567', '100000000000000']) {
    await value.fill(invalid)
    assert.equal(await value.evaluate(input => input.validity.patternMismatch), true, invalid)
  }
  await value.fill('-0.123456')
  assert.equal(await value.evaluate(input => input.validity.valid), true)
  await specification.getByRole('button', { name: 'Save specification' }).click()
  await page.getByRole('cell', { name: '-0.123456 kg', exact: true }).waitFor()

  await tab('Supplier aliases')
  await page.getByText('Filter by supplier or SKU', { exact: true }).click()
  await page.getByLabel('Filter supplier', { exact: true }).selectOption({ label: 'SUP-TEST — Synthetic supplier' })
  await page.getByLabel('Filter SKU', { exact: true }).selectOption(skuId)
  await page.getByLabel('Filter alias status').selectOption('VERIFIED')
  await page.reload()
  await page.getByRole('row').filter({ hasText: 'SOURCE-A3' }).waitFor()
  assert.equal(await page.getByLabel('Filter alias status').inputValue(), 'VERIFIED')
  const aliasUrl = page.url()
  await page.getByRole('button', { name: 'Details ZARF-A3 from alias' }).click()
  await page.getByRole('heading', { name: 'ZARF-A3 — A3 refreshed', exact: true }).waitFor()
  await page.goBack()
  assert.equal(page.url(), aliasUrl)
  await page.getByRole('row').filter({ hasText: 'SOURCE-A3' }).waitFor()
  await page.getByLabel('Filter alias status').selectOption('REJECTED')
  await page.getByText('No matching aliases. Change or clear the filters.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Clear alias filters' }).click()
  await page.getByRole('row').filter({ hasText: 'SOURCE-A3' }).waitFor()

  await page.setViewportSize({ width: 390, height: 844 })
  const selectedTab = page.getByRole('tab', { name: 'Supplier aliases', exact: true })
  await page.waitForFunction(() => {
    const selected = document.querySelector('[role="tab"][aria-selected="true"]').getBoundingClientRect()
    return selected.left >= 0 && selected.right <= innerWidth
  })
  assert.equal(await page.locator('header').count(), 0)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: `${artifacts}/product-ux-mobile.png`, fullPage: true })
  await selectedTab.focus()
  await page.keyboard.press('Home')
  await page.getByRole('tab', { name: 'SKUs', exact: true, selected: true }).waitFor()
  assert.equal(await page.getByRole('tab', { name: 'SKUs', exact: true }).getAttribute('aria-selected'), 'true')
  await page.setViewportSize({ width: 1440, height: 1000 })

  await page.goto(`${base}/products?view=units&units.offset=999999`)
  await page.getByRole('button', { name: 'Back to first page' }).click()
  await page.getByText('1–25 of 27', { exact: true }).waitFor()
  // A failed list can be retried without losing the URL filters.
  const failOnce = route => route.fulfill({ status: 503, json: { error: { code: 'TEST_UNAVAILABLE', message: 'Catalogue temporarily unavailable.' }, requestId: 'product-ux-retry' } })
  await page.route('**/products/units?**', failOnce, { times: 1 })
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: 'Catalogue temporarily unavailable.' }).waitFor()
  await page.getByRole('button', { name: 'Try again', exact: true }).click()
  await page.getByText('1–25 of 27', { exact: true }).waitFor()

  await page.goto(detailUrl)
  await page.getByRole('heading', { name: 'ZARF-A3 — A3 refreshed', exact: true }).waitFor()
  const entity = page.locator('aside').getByLabel('Legal entity')
  const originalEntity = await entity.inputValue()
  const otherEntity = await entity.locator('option').evaluateAll((options, current) => options.find(option => option.value !== current).value, originalEntity)
  await entity.selectOption(otherEntity)
  await page.getByRole('alert').waitFor()
  assert.equal(await page.getByRole('heading', { name: 'ZARF-A3 — A3 refreshed', exact: true }).count(), 0)
  assert.equal(await page.getByRole('heading', { name: 'Specifications', exact: true }).count(), 0)
  await entity.selectOption(originalEntity)
  await page.getByRole('heading', { name: 'ZARF-A3 — A3 refreshed', exact: true }).waitFor()
  await page.screenshot({ path: `${artifacts}/product-ux-detail.png`, fullPage: true })
  await page.goto(`${base}/products?sku=00000000-0000-0000-0000-000000000000`)
  await page.getByRole('alert').waitFor()
  await page.getByRole('button', { name: 'Back to SKUs' }).click()
  await page.getByRole('button', { name: 'Details ZARF-A4', exact: true }).click()
  await page.getByText('This SKU is inactive.', { exact: false }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Save specification' }).count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Add GTİP entry' }).count(), 0)
  console.log('PASS: product URLs/back/reload/refresh, family and alias drill-down, inactive filters, duplicate warnings, required/code/decimal/date validation, paging recovery, retry, mobile keyboard tabs and entity-scoped details.')
}
