import assert from 'node:assert/strict'

export async function checkPurchasing(page, base, artifacts, browser) {
  assert.equal(process.env.SMOKE_ISOLATED, '1')
  await page.goto(`${base}/purchasing?view=partners`)
  await page.getByRole('heading', { name: 'Purchasing', exact: true }).waitFor()
  assert.equal(await page.locator('header').count(), 0)
  await page.getByRole('button', { name: 'New trading partner', exact: true }).click()
  await page.getByLabel('Partner code', { exact: true }).fill('BROWSER-SUP')
  await page.getByLabel('Partner name', { exact: true }).fill('Synthetic purchasing supplier')
  await page.getByLabel('Tax identifier', { exact: true }).fill('1111111111')
  await page.getByLabel('Address', { exact: true }).fill('Synthetic supplier address')
  await page.getByRole('button', { name: 'Save trading partner', exact: true }).click()
  await page.getByRole('heading', { name: 'BROWSER-SUP — Synthetic purchasing supplier', exact: true }).waitFor()
  const partnerId = new URL(page.url()).searchParams.get('id')
  await page.getByRole('button', { name: 'Edit partner', exact: true }).click()
  await page.getByLabel('Phone', { exact: true }).fill('Synthetic phone')
  await page.getByRole('button', { name: 'Save trading partner', exact: true }).click()
  await page.getByText('Synthetic phone', { exact: true }).waitFor()
  const fillCommon = async reference => {
    await page.getByLabel('Document reference', { exact: true }).fill(reference)
    await page.getByLabel('Document date', { exact: true }).fill('2026-10-27')
    await page.getByLabel('EBYS reference', { exact: true }).fill(`EBYS-${reference}`)
    await page.getByLabel('Purchase purpose', { exact: true }).fill('Synthetic multi-item purchasing')
    await page.getByLabel('Commercial terms', { exact: true }).fill('Synthetic agreed terms')
  }
  const reviewer = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  try {
    await reviewer.goto(`${base}/purchasing`)
    await reviewer.getByLabel('Workspace code').fill(process.env.SMOKE_TENANT)
    await reviewer.getByLabel('Email', { exact: true }).fill(process.env.SMOKE_INVENTORY_REVIEWER_EMAIL)
    await reviewer.getByLabel('Password', { exact: true }).fill(process.env.SMOKE_PASSWORD)
    await reviewer.getByRole('button', { name: 'Sign in', exact: true }).click()
    await reviewer.getByRole('heading', { name: 'Purchasing', exact: true }).waitFor()
    assert.equal(await reviewer.getByRole('button', { name: 'New purchase request', exact: true }).count(), 0)
    const approve = async reference => {
      assert.equal(await page.getByRole('button', { name: 'Approve document', exact: true }).isDisabled(), true)
      await reviewer.goto(page.url())
      await reviewer.getByRole('heading', { name: reference, exact: true }).waitFor()
      await reviewer.getByLabel('Purchasing action reason', { exact: true }).fill('Independent source and EBYS evidence checked')
      await reviewer.getByRole('button', { name: 'Approve document', exact: true }).click()
      await reviewer.getByText('APPROVED', { exact: true }).waitFor()
      assert.equal(await reviewer.getByRole('button', { name: 'Cancel document', exact: true }).count(), 0)
      await page.getByRole('button', { name: 'Refresh', exact: true }).click()
      await page.getByText('APPROVED', { exact: true }).waitFor()
    }
    await page.getByRole('tab', { name: 'Contracts', exact: true }).click()
    await page.getByRole('button', { name: 'New contract', exact: true }).click()
    await fillCommon('BROWSER-CONTRACT')
    await page.getByLabel('Supplier partner', { exact: true }).selectOption(partnerId)
    await page.getByLabel('Valid from', { exact: true }).fill('2026-10-01')
    await page.getByLabel('Valid to', { exact: true }).fill('2026-12-31')
    await page.getByRole('button', { name: 'Submit contract', exact: true }).click()
    await page.getByRole('heading', { name: 'BROWSER-CONTRACT', exact: true }).waitFor()
    const contractId = new URL(page.url()).searchParams.get('id')
    await approve('BROWSER-CONTRACT')
    await page.getByRole('tab', { name: 'Purchase requests', exact: true }).click()
    await page.getByRole('button', { name: 'New purchase request', exact: true }).click()
    await fillCommon('BROWSER-REQUEST')
    await page.getByLabel('Required delivery date', { exact: true }).fill('2026-11-15')
    const skus = await page.evaluate(async () => {
      const { apiClient } = await import('/src/api/client.js'), me = (await apiClient.get('/me')).data
      return (await apiClient.get(`/entities/${me.activeEntity.id}/purchasing/skus`, { params: { active: 'true' } })).data.items
    })
    for (const [i, code] of ['ZARF-A3', 'ZARF-A5'].entries()) {
      await page.getByLabel('Requested SKU', { exact: true }).selectOption(skus.find(s => s.code === code).id)
      await page.getByRole('button', { name: 'Add request line', exact: true }).click()
      await page.getByLabel(`Description line-${i + 1}`, { exact: true }).fill(`Original requested ${code}`)
      await page.getByLabel(`Quantity line-${i + 1}`, { exact: true }).fill(i ? '1' : '2')
    }
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: `${artifacts}/purchasing-request-mobile.png`, fullPage: true })
    await page.getByRole('button', { name: 'Submit purchase request', exact: true }).click()
    await page.getByRole('heading', { name: 'BROWSER-REQUEST', exact: true }).waitFor()
    const requestId = new URL(page.url()).searchParams.get('id')
    await page.setViewportSize({ width: 1440, height: 1000 })
    await approve('BROWSER-REQUEST')
    await page.getByRole('tab', { name: 'Purchase orders', exact: true }).click()
    await page.getByRole('button', { name: 'New purchase order', exact: true }).click()
    await fillCommon('BROWSER-ORDER')
    await page.getByLabel('Required delivery date', { exact: true }).fill('2026-11-15')
    await page.getByLabel('Supplier partner', { exact: true }).selectOption(partnerId)
    await page.getByLabel('Approved purchase request', { exact: true }).selectOption(requestId)
    await page.getByLabel('Approved contract (optional)', { exact: true }).selectOption(contractId)
    for (const i of [1, 2]) {
      await page.getByRole('button', { name: `Add order line line-${i}`, exact: true }).click()
      await page.getByLabel(`Quantity line-${i}`, { exact: true }).fill('1')
      await page.getByLabel(`Unit price line-${i}`, { exact: true }).fill(i === 1 ? '125.5' : '0')
    }
    assert.equal(await page.getByRole('button', { name: 'Submit purchase order', exact: true }).isDisabled(), true)
    await page.getByLabel('Free-goods reason line-2', { exact: true }).fill('Approved free sample')
    await page.getByText('Order net preview: 125.500000 TRY. Excludes invoice VAT and currency conversion.', { exact: true }).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: `${artifacts}/purchasing-order-form-mobile.png`, fullPage: true })
    await page.getByRole('button', { name: 'Submit purchase order', exact: true }).click()
    await page.getByRole('heading', { name: 'BROWSER-ORDER', exact: true }).waitFor()
    await page.setViewportSize({ width: 1440, height: 1000 })
    await approve('BROWSER-ORDER')
    const orderUrl = page.url()
    await page.reload()
    await page.getByText('Order net total: 125.500000 TRY. No invoice, stock or journal has been posted by this order.', { exact: true }).waitFor()
    await page.screenshot({ path: `${artifacts}/purchasing-order-desktop.png`, fullPage: true })
    await page.getByRole('link', { name: 'Source purchase request', exact: true }).click()
    await page.getByRole('heading', { name: 'BROWSER-REQUEST', exact: true }).waitFor()
    await page.getByLabel('Purchasing action reason', { exact: true }).fill('Attempt cancellation with active order')
    await page.getByRole('button', { name: 'Cancel document', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: 'Cancel dependent orders first.' }).waitFor()
    await page.goBack()
    assert.equal(page.url(), orderUrl)
    await page.getByRole('heading', { name: 'BROWSER-ORDER', exact: true }).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: `${artifacts}/purchasing-order-detail-mobile.png`, fullPage: true })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('tab', { name: 'Audit trail', exact: true }).click()
    await page.getByRole('cell', { name: /purchasing.orders.approve/ }).waitFor()
    await page.locator('aside').getByLabel('Legal entity').selectOption({ label: 'Alpha one' })
    await page.goto(orderUrl)
    await page.getByRole('alert').filter({ hasText: 'Record not found in this entity.' }).waitFor()
    await page.locator('aside').getByLabel('Legal entity').selectOption(process.env.SMOKE_SECOND_ENTITY)
    await page.goto(orderUrl)
    await page.getByRole('heading', { name: 'BROWSER-ORDER', exact: true }).waitFor()
  } finally { await reviewer.close() }
  console.log('PASS: trading partner, EBYS contract/request/order, two SKUs, free goods, exact totals, independent reviewer, source drilldown, cancellation guard, audit, reload/back, mobile forms and entity isolation.')
}

export async function checkPurchasingReader(page, base) {
  await page.goto(`${base}/purchasing?view=orders`)
  await page.getByRole('heading', { name: 'Purchasing', exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'New purchase order', exact: true }).count(), 0)
  assert.equal(await page.getByRole('tab', { name: 'Audit trail', exact: true }).count(), 0)
  await page.getByRole('button', { name: 'View BROWSER-ORDER', exact: true }).click()
  await page.getByRole('heading', { name: 'BROWSER-ORDER', exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: /Approve document|Reject document|Cancel document/ }).count(), 0)
  await page.getByRole('tab', { name: 'Trading partners', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: 'New trading partner', exact: true }).count(), 0)
  console.log('PASS: purchasing reader can inspect supplier and retained order details without write, approval or audit controls.')
}
