import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
import {invoiceXml} from '../../backend/tests/invoice-xml-fixture.js'

export async function checkInvoices(page,base,artifacts,browser){
  assert.equal(process.env.SMOKE_ISOLATED,'1')
  await page.goto(`${base}/purchasing?view=invoices`)
  await page.getByRole('heading',{name:'Purchasing',exact:true}).waitFor()
  await page.getByRole('button',{name:'Configure recipient identity',exact:true}).click()
  await page.getByLabel('Receiving tax identifier',{exact:true}).fill('2222222222')
  await page.getByLabel('Recipient configuration reason',{exact:true}).fill('Synthetic browser company identity')
  await page.getByRole('button',{name:'Save recipient identity',exact:true}).click()
  await page.getByText('VKN: 2222222222',{exact:true}).waitFor()
  const data=await page.evaluate(async()=>{const {apiClient}=await import('/src/api/client.js'),me=(await apiClient.get('/me')).data,base=`/entities/${me.activeEntity.id}/purchasing`;const partner=(await apiClient.get(base+'/partners',{params:{q:'BROWSER-SUP'}})).data.items[0],order=(await apiClient.get(base+'/orders',{params:{q:'BROWSER-ORDER'}})).data.items[0],lines=(await apiClient.get(base+`/orders/${order.id}/lines`)).data.items;return {base,partner,order,lines}})
  const xml=invoiceXml({number:'BROWSER-INVOICE',orderReference:'BROWSER-ORDER',lines:[{code:'SOURCE-A3',name:'Original supplier A3 item',quantity:'1',price:'125.5',rate:'10'},{code:'SOURCE-A5',name:'Original free sample',quantity:'1',price:'0',rate:'0'}]})
  await page.getByRole('button',{name:'Import invoice XML',exact:true}).click()
  await page.getByLabel('Invoice XML file',{exact:true}).setInputFiles({name:'synthetic-purchase.xml',mimeType:'text/xml',buffer:Buffer.from(xml)})
  await page.getByLabel('Import evidence reference',{exact:true}).fill('Synthetic supplier purchase invoice export')
  await page.getByRole('button',{name:'Stage invoice XML',exact:true}).click()
  await page.getByRole('heading',{name:'Invoice BROWSER-INVOICE',exact:true}).waitFor()
  const invoiceUrl=page.url(),invoiceId=new URL(invoiceUrl).searchParams.get('id')
  await page.getByLabel('Invoice supplier partner',{exact:true}).selectOption(data.partner.id)
  await page.getByLabel('Invoice approved order',{exact:true}).selectOption(data.order.id)
  await page.getByLabel('Select invoice line 1',{exact:true}).check()
  await page.getByText('Bulk map selected lines (1)',{exact:true}).click()
  await page.getByLabel('Bulk approved order line',{exact:true}).selectOption(data.lines[0].id)
  await page.getByRole('button',{name:'Apply to selected lines',exact:true}).click()
  await page.getByLabel('Approved order line 2',{exact:true}).selectOption(data.lines[1].id)
  await page.getByLabel('Confirm base unit 2',{exact:true}).check()
  await page.getByLabel('Invoice free-goods reason 2',{exact:true}).fill('Retained approved free sample')
  await page.getByLabel('Invoice mapping reason',{exact:true}).fill('Synthetic bulk and manual source matching')
  await page.setViewportSize({width:390,height:844})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  await page.waitForFunction(()=>{const tab=document.querySelector('[role="tab"][aria-selected="true"]'),list=tab?.parentElement;if(!list)return false;const a=tab.getBoundingClientRect(),b=list.getBoundingClientRect();return a.left>=b.left-1&&a.right<=b.right+1})
  await page.screenshot({path:`${artifacts}/invoice-mapping-mobile.png`,fullPage:true})
  await page.getByRole('button',{name:'Save mapping revision',exact:true}).click()
  await page.getByText('UNIT_CONFIRMATION · Line 1',{exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:'Submit invoice matching',exact:true}).isDisabled(),true)
  await page.getByLabel('Confirm base unit 1',{exact:true}).check()
  await page.getByLabel('Invoice mapping reason',{exact:true}).fill('Confirmed C62 means one catalogue base unit')
  await page.getByRole('button',{name:'Save mapping revision',exact:true}).click()
  await page.getByText('All source and matching checks pass.',{exact:true}).waitFor()
  await page.setViewportSize({width:1440,height:1000})
  await page.getByLabel('Invoice action reason',{exact:true}).fill('Submit preserved source and order matching')
  await page.getByRole('button',{name:'Submit invoice matching',exact:true}).click()
  await page.getByText('REQUESTED',{exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:'Approve invoice matching',exact:true}).isDisabled(),true)
  const reviewer=await browser.newPage({viewport:{width:1440,height:1000}})
  try{
    await reviewer.goto(invoiceUrl)
    await reviewer.getByLabel('Workspace code').fill(process.env.SMOKE_TENANT)
    await reviewer.getByLabel('Email',{exact:true}).fill(process.env.SMOKE_INVENTORY_REVIEWER_EMAIL)
    await reviewer.getByLabel('Password',{exact:true}).fill(process.env.SMOKE_PASSWORD)
    await reviewer.getByRole('button',{name:'Sign in',exact:true}).click()
    await reviewer.getByRole('heading',{name:'Invoice BROWSER-INVOICE',exact:true}).waitFor()
    assert.equal(await reviewer.getByRole('heading',{name:'Map invoice source lines',exact:true}).count(),0)
    await reviewer.getByLabel('Invoice action reason',{exact:true}).fill('Independent original XML and matching review')
    await reviewer.getByRole('button',{name:'Approve invoice matching',exact:true}).click()
    await reviewer.getByText('READY',{exact:true}).waitFor()
    await reviewer.getByLabel('Invoice action reason',{exact:true}).fill('Return matching for another independent review cycle')
    await reviewer.getByRole('button',{name:'Return for mapping revision',exact:true}).click()
    await reviewer.getByText('STAGED',{exact:true}).waitFor()
    await page.getByRole('button',{name:'Refresh',exact:true}).click()
    await page.getByText('STAGED',{exact:true}).waitFor()
    await page.getByLabel('Invoice action reason',{exact:true}).fill('Resubmit current matching after retained review')
    await page.getByRole('button',{name:'Submit invoice matching',exact:true}).click()
    await page.getByText('REQUESTED',{exact:true}).waitFor()
    await reviewer.getByRole('button',{name:'Refresh',exact:true}).click()
    await reviewer.getByLabel('Invoice action reason',{exact:true}).fill('Approve retained source matching again')
    await reviewer.getByRole('button',{name:'Approve invoice matching',exact:true}).click()
    await reviewer.getByText('READY',{exact:true}).waitFor()
  }finally{await reviewer.close()}
  await page.getByRole('button',{name:'Refresh',exact:true}).click()
  await page.getByText('READY',{exact:true}).waitFor()
  await page.screenshot({path:`${artifacts}/invoice-ready-desktop.png`,fullPage:true})
  const downloadEvent=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download original XML',exact:true}).click()
  const download=await downloadEvent
  assert.equal(await readFile(await download.path(),'utf8'),xml)
  await page.getByText('Mapping revision history',{exact:true}).click()
  await page.getByRole('button',{name:'Inspect invoice mapping 1',exact:true}).click()
  await page.getByRole('heading',{name:'Retained invoice lines · Mapping revision 1',exact:true}).waitFor()
  await page.getByRole('cell').filter({hasText:'Source unit retained'}).waitFor()
  await page.getByRole('button',{name:'Current mapping lines',exact:true}).click()
  await page.reload()
  await page.getByText('READY',{exact:true}).waitFor()
  const duplicate=await page.evaluate(async({base,xml})=>{const {apiClient}=await import('/src/api/client.js');return (await apiClient.post(base+'/invoices',{xml,fileName:'duplicate.xml',evidence:'Same original source'},{headers:{'Idempotency-Key':crypto.randomUUID()}})).data},{base:data.base,xml})
  assert.equal(duplicate.item.id,invoiceId);assert.equal(duplicate.duplicate,true)
  await page.getByRole('link',{name:'Matched purchase order',exact:true}).click()
  await page.getByLabel('Purchasing action reason',{exact:true}).fill('Attempt cancelling matched order')
  await page.getByRole('button',{name:'Cancel document',exact:true}).click()
  await page.getByRole('alert').filter({hasText:'Cancel linked invoice matching before cancelling this order.'}).waitFor()
  await page.goBack()
  await page.getByRole('heading',{name:'Invoice BROWSER-INVOICE',exact:true}).waitFor()
  await page.setViewportSize({width:390,height:844})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  await page.screenshot({path:`${artifacts}/invoice-ready-mobile.png`,fullPage:true})
  await page.setViewportSize({width:1440,height:1000})
  await page.locator('aside').getByLabel('Legal entity').selectOption({label:'Alpha one'})
  await page.goto(invoiceUrl)
  await page.getByRole('alert').filter({hasText:'Record not found in this entity.'}).first().waitFor()
  await page.locator('aside').getByLabel('Legal entity').selectOption(process.env.SMOKE_SECOND_ENTITY)
  await page.goto(invoiceUrl)
  await page.getByText('READY',{exact:true}).waitFor()
  console.log('PASS: incoming XML import, recipient identity, bulk/manual multi-item mapping, free goods/mixed VAT, unit guard, retained revisions/download, duplicate UUID, independent review, order cancellation guard, reload, mobile and scope.')
}
export async function checkInvoiceReader(page,base){
  await page.goto(`${base}/purchasing?view=invoices`)
  await page.getByRole('heading',{name:'Purchasing',exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:'Import invoice XML',exact:true}).count(),0)
  assert.equal(await page.getByRole('button',{name:'Configure recipient identity',exact:true}).count(),0)
  await page.getByRole('button',{name:'View invoice BROWSER-INVOICE',exact:true}).click()
  await page.getByRole('heading',{name:'Invoice BROWSER-INVOICE',exact:true}).waitFor()
  await page.getByText('READY',{exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:/Submit invoice matching|Approve invoice matching|Cancel invoice matching|Save mapping revision/}).count(),0)
  console.log('PASS: purchasing reader can inspect invoice source and validation without import/configuration/mapping/review controls.')
}
