import assert from 'node:assert/strict'

export async function checkProducts(page, base, artifacts) {
  assert.equal(process.env.SMOKE_ISOLATED, '1')
  await page.goto(`${base}/products`)
  await page.getByRole('heading', { name: 'Product catalogue' }).waitFor()
  const tab = name => page.getByRole('tab', { name, exact: true }).click()
  await tab('Units of measure')
  await page.getByRole('button', { name: 'Add unit', exact: true }).click()
  await page.getByLabel('Code', { exact: true }).fill('EA')
  await page.getByLabel('Name', { exact: true }).fill('Adet')
  await page.getByLabel('Symbol', { exact: true }).fill('ad')
  await page.getByRole('button', { name: 'Save unit', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'EA' }).waitFor()
  await tab('Product families')
  await page.getByRole('button', { name: 'Add family', exact: true }).click()
  await page.getByLabel('Code', { exact: true }).fill('ZARF')
  await page.getByLabel('Name', { exact: true }).fill('Zarf')
  await page.getByRole('button', { name: 'Save family', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'ZARF' }).waitFor()
  await tab('SKUs')
  for (const code of ['ZARF-A4', 'ZARF-A3']) {
    await page.getByRole('button', { name: 'Add SKU', exact: true }).click()
    await page.getByLabel('Code', { exact: true }).fill(code)
    await page.getByLabel('Name', { exact: true }).fill(`${code} envelope`)
    await page.getByLabel('Description', { exact: true }).fill('Synthetic browser fixture')
    await page.getByLabel('Product family', { exact: true }).selectOption({ label: 'ZARF — Zarf' })
    await page.getByLabel('Base unit', { exact: true }).selectOption({ label: 'EA — Adet' })
    await page.getByRole('button', { name: 'Save SKU', exact: true }).click()
    await page.getByRole('row').filter({ hasText: code }).waitFor()
  }
  assert.equal(await page.getByRole('row').count(), 3)
  await page.getByRole('button', { name: 'Edit ZARF-A4', exact: true }).click()
  assert.equal(await page.getByLabel('Code', { exact: true }).isDisabled(), true)
  assert.equal(await page.getByLabel('Base unit', { exact: true }).isDisabled(), true)
  await page.getByLabel('Name', { exact: true }).fill('A4 updated')
  await page.getByLabel('Status', { exact: true }).selectOption('false')
  await page.getByRole('button', { name: 'Save SKU', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'A4 updated' }).waitFor()
  await page.getByLabel('Filter status').selectOption('false')
  await page.getByRole('row').filter({ hasText: 'A4 updated' }).waitFor()
  assert.equal(await page.getByRole('row').count(), 2)
  await page.getByLabel('Filter status').selectOption('')
  await page.getByRole('row').filter({ hasText: 'ZARF-A3' }).waitFor()
  await page.getByLabel('Search catalogue').fill('A3')
  await page.getByRole('row').filter({ hasText: 'ZARF-A3' }).waitFor()
  assert.equal(await page.getByRole('row').count(), 2)
  await page.getByLabel('Search catalogue').fill('')
  await page.getByRole('row').filter({ hasText: 'A4 updated' }).waitFor()
  // The API retains inactive codes; an attempted duplicate stays editable.
  await page.getByRole('button', { name: 'Add SKU', exact: true }).click()
  await page.getByLabel('Code', { exact: true }).fill('ZARF-A4')
  await page.getByRole('status').filter({ hasText: 'Code ZARF-A4 already exists (inactive)' }).waitFor()
  await page.getByLabel('Name', { exact: true }).fill('Duplicate')
  await page.getByLabel('Product family', { exact: true }).selectOption({ label: 'ZARF — Zarf' })
  await page.getByLabel('Base unit', { exact: true }).selectOption({ label: 'EA — Adet' })
  await page.getByRole('button', { name: 'Save SKU', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: 'already exists' }).waitFor()
  assert.equal(await page.getByLabel('Name', { exact: true }).inputValue(), 'Duplicate')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await tab('Units of measure')
  await page.getByRole('button', { name: 'Edit EA', exact: true }).click()
  await page.getByLabel('Status', { exact: true }).selectOption('false')
  await page.getByRole('button', { name: 'Save unit', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: 'Deactivate the active SKUs' }).waitFor()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  // Populate only the disposable schema to exercise list and selector paging.
  await page.evaluate(async () => {
    const { apiClient } = await import('/src/api/client.js')
    const { data: profile } = await apiClient.get('/me')
    for (let index = 0; index < 26; index++) await apiClient.post(`/entities/${profile.activeEntity.id}/products/units`,
      { code: `UNIT-${String(index).padStart(2, '0')}`, name: `Fixture ${index}`, symbol: 'u', quantityPrecision: 0 },
      { headers: { 'Idempotency-Key': crypto.randomUUID() } })
  })
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await page.getByText('1–25 of 27', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  await page.getByText('26–27 of 27', { exact: true }).waitFor()
  await tab('SKUs')
  await page.getByRole('button', { name: 'Add SKU', exact: true }).click()
  await page.getByLabel('Code', { exact: true }).fill('PAGING-CHECK')
  await page.getByLabel('Name', { exact: true }).fill('Paging check')
  await page.getByLabel('Product family', { exact: true }).selectOption({ label: 'ZARF — Zarf' })
  const unitGroup = page.getByRole('group', { name: 'Base unit', exact: true })
  await unitGroup.getByLabel('Base unit', { exact: true }).selectOption({ label: 'EA — Adet' })
  const selectedId = await unitGroup.getByLabel('Base unit', { exact: true }).inputValue()
  await unitGroup.getByRole('button', { name: 'Next', exact: true }).click()
  await unitGroup.getByText('26–27 of 27', { exact: true }).waitFor()
  assert.equal(await unitGroup.getByLabel('Base unit', { exact: true }).inputValue(), selectedId)
  assert.equal(await page.getByRole('heading', { name: 'Add SKU', exact: true }).count(), 1)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await tab('Audit trail')
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  await page.getByRole('cell', { name: 'product.skus.updated', exact: true }).waitFor()
  await page.screenshot({ path: `${artifacts}/products-audit.png`, fullPage: true })
  await tab('SKUs')
  await page.reload()
  await page.getByRole('row').filter({ hasText: 'A4 updated' }).waitFor()
  await page.screenshot({ path: `${artifacts}/products-desktop.png`, fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Add SKU', exact: true }).click()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.equal(await page.locator('header').count(), 0)
  await page.screenshot({ path: `${artifacts}/products-mobile.png`, fullPage: true })
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 1000 })
  console.log('PASS: product units/families/A4+A3, edit/inactive, duplicate/in-use errors, filtering, paged selector retention without submission, audit, reload and mobile layout.')
}
